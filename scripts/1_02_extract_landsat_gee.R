# stack test points
outpoints <- lapply(list.files(path_to_points, full.names = TRUE, pattern = ".csv"), function(x) {
  print(x)
  tblpts <- readr::read_csv(x)
  tblpts <- tblpts %>%
    rename(point_number = `system:index`) %>%
    # resolve duplicate point names by adding seed as suffix
    mutate(point_number = paste0(
      str_extract(x, "(seed_\\d{1,5})"), "_",
      point_number
    ))
  return(tblpts)
})

