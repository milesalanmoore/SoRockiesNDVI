trainingcoords <-
  trainingcoords %>%
  dplyr::mutate(
    max_fcp = pmax(vcf_2000, vcf_2005, vcf_2010, vcf_2015, na.rm = TRUE),
    mean_fcp = rowMeans(select(., vcf_2000, vcf_2005, vcf_2010, vcf_2015), na.rm = TRUE)
  )

